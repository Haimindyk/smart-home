export const wellnessExercises: CatalogExercise[] = rows.map(
  ([id, he, en, muscle, equipment, pattern, hasDemo]) => ({
    id,
    he,
    en,
    muscle,
    equipment,
    pattern,
    ...(hasDemo ? { demoId: id } : {}),
  }),
);
export function resolveCatalogExercise(name: string, id?: string) {
  return (
    wellnessExercises.find((e) => e.id === id) ??
    wellnessExercises.find((e) =>
      [e.he, e.en, e.id].some(
        (n) => n.toLocaleLowerCase() === name.trim().toLocaleLowerCase(),
      ),
    )
  );
}
